function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function randBudget(): { budget_min: number; budget_max: number } {
  const ranges = [
    [10000, 30000], [20000, 60000], [30000, 80000], [50000, 150000],
    [80000, 200000], [100000, 300000], [150000, 500000], [200000, 700000],
    [300000, 1000000], [500000, 1500000],
  ];
  const [min, max] = pick(ranges);
  return { budget_min: min, budget_max: max };
}

function futureDate(daysMin: number, daysMax: number): string {
  const days = daysMin + Math.floor(Math.random() * (daysMax - daysMin));
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d.toISOString().split("T")[0];
}

// A deterministic "system" user id for auto-generated listings
const SYSTEM_USER_ID = "00000000-0000-0000-0000-000000000000";

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  try {
    const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
    const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
    const supabase = createClient(supabaseUrl, serviceRoleKey);

    // Ensure the system user exists in profiles
    const { data: profileExists } = await supabase
      .from("profiles")
      .select("id")
      .eq("user_id", SYSTEM_USER_ID)
      .maybeSingle();

    if (!profileExists) {
      await supabase.from("profiles").insert({
        user_id: SYSTEM_USER_ID,
        display_name: "STRUKTURA Bot",
      });
    }

    // Generate 1-3 listings
    const count = 1 + Math.floor(Math.random() * 3);
    const categories = Object.keys(TITLES);
    const listings = [];

    for (let i = 0; i < count; i++) {
      const cat = pick(categories);
      const { budget_min, budget_max } = randBudget();
      const hasDeadline = Math.random() > 0.3;

      listings.push({
        user_id: SYSTEM_USER_ID,
        title: pick(TITLES[cat]),
        description: pick(DESCRIPTIONS[cat]),
        category: cat,
        budget_min,
        budget_max,
        deadline: hasDeadline ? futureDate(7, 60) : null,
        address: pick(ADDRESSES),
        status: "active",
      });
    }

    const { error } = await supabase.from("listings").insert(listings);

    if (error) {
      console.error("Insert error:", error);
      return new Response(JSON.stringify({ error: error.message }), {
        status: 500,
        headers: { ...corsHeaders, "Content-Type": "application/json" },
      });
    }

    return new Response(
      JSON.stringify({ success: true, generated: listings.length }),
      { headers: { ...corsHeaders, "Content-Type": "application/json" } }
    );
  } catch (err) {
    console.error("Error:", err);
    return new Response(JSON.stringify({ error: String(err) }), {
      status: 500,
      headers: { ...corsHeaders, "Content-Type": "application/json" },
    });
  }
});
